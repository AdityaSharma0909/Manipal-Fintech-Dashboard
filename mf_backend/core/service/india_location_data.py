def normalize_state_name(state_name):
    return " ".join((state_name or "").strip().lower().split())


def get_all_states_and_uts():
    return sorted(INDIA_STATES_AND_UT_DISTRICTS.keys())


def get_state_code(state_name):
    return INDIA_STATE_UT_CODES.get(state_name)


def get_all_states_uts_with_codes():
    return [
        {
            "state": state,
            "state_code": get_state_code(state)
        }
        for state in get_all_states_and_uts()
    ]


def normalize_state_code(state_code):
    return (state_code or "").strip().upper()


def find_districts_by_state_code(state_code):
    normalized_code = normalize_state_code(state_code)
    if not normalized_code:
        return []

    for state, code in INDIA_STATE_UT_CODES.items():
        if code == normalized_code:
            return [
                {
                    "state": state,
                    "state_code": code,
                    "districts": sorted(INDIA_STATES_AND_UT_DISTRICTS.get(state, [])),
                }
            ]

    return []


def find_districts_by_state(state_name):
    normalized_input = normalize_state_name(state_name)
    if not normalized_input:
        return []

    exact_match = []
    partial_match = []

    for state, districts in INDIA_STATES_AND_UT_DISTRICTS.items():
        normalized_state = normalize_state_name(state)
        if normalized_state == normalized_input:
            exact_match.append(
                {
                    "state": state,
                    "state_code": get_state_code(state),
                    "districts": sorted(districts)
                }
            )
            continue
        if normalized_input in normalized_state:
            partial_match.append(
                {
                    "state": state,
                    "state_code": get_state_code(state),
                    "districts": sorted(districts)
                }
            )

    return exact_match if exact_match else partial_match
